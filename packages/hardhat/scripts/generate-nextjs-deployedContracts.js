const fs = require("fs");
const path = require("path");

const deploymentsRoot = path.resolve(__dirname, "../deployments");
const outputPath = path.resolve(__dirname, "../../nextjs/contracts/deployedContracts.ts");

const EXCLUDED_FILES = new Set([".chainId"]);

function readJson(filePath) {
  return JSON.parse(fs.readFileSync(filePath, "utf8"));
}

function getChainId(folderPath, networkName) {
  const chainIdFile = path.join(folderPath, ".chainId");
  if (fs.existsSync(chainIdFile)) {
    const raw = fs.readFileSync(chainIdFile, "utf8").trim();
    const parsed = Number(raw);
    if (!Number.isNaN(parsed)) return parsed;
  }

  if (networkName === "thunder") return 108;
  if (networkName === "testthunder") return 18;
  return null;
}

function buildContracts() {
  const result = {};

  if (!fs.existsSync(deploymentsRoot)) {
    return result;
  }

  const networks = fs
    .readdirSync(deploymentsRoot, { withFileTypes: true })
    .filter(d => d.isDirectory())
    .map(d => d.name);

  for (const networkName of networks) {
    const networkPath = path.join(deploymentsRoot, networkName);
    const chainId = getChainId(networkPath, networkName);
    if (!chainId) continue;

    const files = fs
      .readdirSync(networkPath)
      .filter(file => file.endsWith(".json") && !EXCLUDED_FILES.has(file));

    const contracts = {};

    for (const file of files) {
      const fullPath = path.join(networkPath, file);
      const json = readJson(fullPath);
      if (!json.address || !json.abi) continue;

      const name = path.basename(file, ".json");
      contracts[name] = {
        address: json.address,
        abi: json.abi,
      };

      if (json.receipt?.blockNumber) {
        contracts[name].deployedOnBlock = Number(json.receipt.blockNumber);
      }
    }

    if (Object.keys(contracts).length > 0) {
      result[chainId] = contracts;
    }
  }

  return result;
}

function writeOutput(data) {
  const content = `/**\n * This file is autogenerated by scripts/generate-nextjs-deployedContracts.js\n * Do not edit manually. Run \"yarn deploy\" in packages/hardhat to regenerate.\n */\nimport { GenericContractsDeclaration } from \"~~/utils/scaffold-eth/contract\";\n\nconst deployedContracts = ${JSON.stringify(
    data,
    null,
    2,
  )} as const;\n\nexport default deployedContracts satisfies GenericContractsDeclaration;\n`;

  fs.writeFileSync(outputPath, content);
}

const data = buildContracts();
writeOutput(data);
console.log(`✅ Wrote Next.js deployed contracts: ${outputPath}`);
